const listeners = new Set<() => void>()
const arabicByEnglish = new Map(Object.entries(english).map(([arabic, translated]) => [translated, arabic]))
function readLocale(): AppLocale {
  try { return localStorage.getItem(STORAGE_KEY) === 'ar' ? 'ar' : 'en' } catch { return 'en' }
}

let locale: AppLocale = readLocale()
if (typeof document !== 'undefined') {
  document.documentElement.lang = locale
  document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr'
}

function subscribe(listener: () => void) {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

function notifyLocale() {
  for (const listener of listeners) listener()
}

export function getLocale(): AppLocale { return locale }
export function direction(): 'rtl' | 'ltr' { return locale === 'ar' ? 'rtl' : 'ltr' }

export function setLocale(next: AppLocale) {
  if (locale === next) return
  locale = next
  persistPreference(preferenceKeys.locale, next)
  if (typeof document !== 'undefined') {
    document.documentElement.lang = next
    document.documentElement.dir = direction()
  }
  notifyLocale()
}

export function toggleLocale() { setLocale(locale === 'en' ? 'ar' : 'en') }

export function useLocale(): AppLocale {
  return useSyncExternalStore(subscribe, () => locale, () => 'en')
}

export function tr(source: string | null | undefined, values: Array<string | number> = []): string {
  const key = source ?? ''
  let translated = locale === 'en' ? english[key] ?? key : arabicByEnglish.get(key) ?? key
  return translated.replace(/\{\{(\d+)\}\}/g, (_match, index: string) => String(values[Number(index)] ?? ''))
}
